import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const site = new URL('../web/', import.meta.url);
const source = readFileSync(new URL('nav.js', site), 'utf8');

function boot({ search = '', readyState = 'loading', origin = 'http://127.0.0.1:43110' } = {}) {
  class Input { value = 'ws://old:2567'; }
  const elements = { server: new Input() }, documentEvents = {}, windowEvents = {};
  elements.server.parentElement = { append(element) { elements[element.id] = element; } };
  const document = {
    readyState, pointerLockElement: null,
    getElementById(id) { return elements[id] ?? null; },
    createElement(tag) {
      return {
        tag, children: [],
        setAttribute(key, value) { this[key] = value; },
        append(...children) { this.children.push(...children); },
        addEventListener(key, value) { this[key] = value; },
      };
    },
    body: { append(element) { elements[element.id] = element; } },
    addEventListener(key, value) { documentEvents[key] = value; },
  };
  const window = { addEventListener(key, value) { const previous = windowEvents[key]; windowEvents[key] = previous ? (() => { previous(); value(); }) : value; } };
  const context = vm.createContext({ document, window, HTMLInputElement: Input, URLSearchParams, location: { search, origin } });
  vm.runInContext(source, context);
  return { elements, document, documentEvents, windowEvents, context };
}

test('home link is native navigation and injection is idempotent', () => {
  const state = boot(), nav = state.elements['parhelion-home-nav'];
  assert.equal(nav.children[0].href, '/');
  assert.equal(nav['aria-label'], 'Parhelion 导航');
  vm.runInContext(source, state.context);
  assert.equal(state.elements['parhelion-home-nav'], nav);
});

test('pointer lock hides navigation; Escape release and page restore reveal it', () => {
  const state = boot(), nav = state.elements['parhelion-home-nav'];
  assert.equal(nav.hidden, false);
  state.document.pointerLockElement = {};
  state.documentEvents.pointerlockchange();
  assert.equal(nav.hidden, true);
  state.document.pointerLockElement = null;
  state.documentEvents.pointerlockchange();
  assert.equal(nav.hidden, false);
  state.windowEvents.pageshow();
  assert.equal(nav.hidden, false);
  assert.equal(state.documentEvents.keydown, undefined, 'never intercept game keys');
});

test('server field points to same-origin WebSocket including selected port', () => {
  const state = boot();
  assert.equal(state.elements.server.value, 'ws://127.0.0.1:43110');
  state.elements.server.value = 'ws://old:2567'; // Original module may finish later.
  state.windowEvents.load();
  assert.equal(state.elements.server.value, 'ws://127.0.0.1:43110');
  assert.equal(boot({ origin: 'https://example.test' }).elements.server.value, 'wss://example.test');
});

test('explicit server query is respected and already-loaded page initializes', () => {
  const explicit = boot({ search: '?server=ws://custom:4000' });
  assert.equal(explicit.elements.server.value, 'ws://old:2567');
  assert.ok(explicit.elements['parhelion-online-note']);
  const loaded = boot({ readyState: 'complete' });
  assert.equal(loaded.windowEvents.load, undefined);
  assert.equal(loaded.elements.server.value, 'ws://127.0.0.1:43110');
});

test('landing links both games, every chapter map and every World region with local assets only', () => {
  const html = readFileSync(new URL('index.html', site), 'utf8');
  assert.match(html, /href="\/arena\/"/);
  assert.match(html, /href="\/world\/"/);
  assert.match(html, /lang="zh-CN"/);
  assert.doesNotMatch(html.replace('<script type="module" src="/site/home-language.js"></script>', ''), /<iframe|<canvas|<script|https?:\/\//);
  // home-language.js is generated by the build; every other referenced file is source.
  for (const [, asset] of html.matchAll(/(?:src|href)="\/site\/([^"#]+)"/g)) {
    if (asset !== 'home-language.js') assert.ok(statSync(fileURLToPath(new URL(asset, site))).isFile(), asset);
  }
  for (const [, asset] of readFileSync(new URL('style.css', site), 'utf8').matchAll(/url\(\/site\/([^)]+)\)/g)) {
    assert.ok(statSync(fileURLToPath(new URL(asset, site))).isFile(), asset);
  }
  for (const id of ['aster', 'camlann', 'blackflag', 'frostcourt', 'sakura']) assert.match(html, new RegExp(`href="/arena/\\?map=${id}"`));
  for (const id of ['britain', 'blacksail', 'winter', 'kyoto']) assert.match(html, new RegExp(`href="/world/\\?region=${id}"`));
  assert.doesNotMatch(html, /neon|zenith|夜港|日冕/i);
});


import { build } from '../arena-game/node_modules/esbuild/lib/main.js';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs/promises';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const out = path.resolve(root, 'site/generated');
await fs.mkdir(out, { recursive: true });
await build({ entryPoints: [path.join(root, 'site/home.ts')], outfile: path.join(out, 'home-language.js'), bundle: true, format: 'esm', target: 'es2022', minify: true });
await fs.copyFile(path.join(root, 'site/language.css'), path.join(out, 'language.css'));
console.log('Built homepage localization only. Nothing was deployed.');
